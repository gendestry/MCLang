    void McGen::visit(ImcMOVE &s) {
        if (auto *temp = dynamic_cast<ImcTEMP *>(s.dst.get())) {
            copy("$" + temp->temp.toString(), gen(*s.src));
            return;
        }

        auto *mem = dynamic_cast<ImcMEM *>(s.dst.get());
        if (!mem) {
            error("MOVE into neither a MEM nor a TEMP: " + s.toString());
            return;
        }

        // A call runs first: it clobbers every scratch holder.
        const bool isCall = dynamic_cast<ImcCALL *>(s.src.get()) != nullptr;
        std::string value = isCall ? gen(*s.src) : "";
        const std::string address = gen(*mem->addr);

        if (mem->size > SLOT_SIZE) {
            auto *source = dynamic_cast<ImcMEM *>(s.src.get());
            if (!source) {
                error("a record-sized MOVE from something not in memory: " + s.toString());
                return;
            }
            copySlots(address, gen(*source->addr), mem->size);
            return;
        }
        if (!isCall)
            value = gen(*s.src);
        store(address, value);
    }

    void McGen::visit(ImcESTMT &s) { gen(*s.expr); }

    // A command with no holes runs as it stands. One with holes becomes a function
    // macro: each value goes into storage mcl:args as a plain number -- a double,
    // so 37.5 arrives as 37.5 and 3 as 3 -- and the macro puts them into the text.
    //
    // When the value is kept, `execute store` catches the command's success or
    // result (a macro passes its command's back through `return run`), and it is
    // scaled into fixed point like every other number.
    void McGen::visit(ImcCMD &s) {
        std::string run = s.text;
        if (!s.args.empty()) {
            std::vector<std::string> holders(s.args.size());
            for (std::size_t i = 0; i < s.args.size(); ++i)
                if (!m_optimize || !dynamic_cast<ImcCONST *>(s.args[i].get()))
                    holders[i] = gen(*s.args[i]);

            for (std::size_t i = 0; i < holders.size(); ++i) {
                const std::string at = "storage mcl:args a" + std::to_string(i);
                if (const auto *c = dynamic_cast<ImcCONST *>(s.args[i].get()); m_optimize && c)
                    emit("data modify " + at + " set value " + decimal(c->value) + "d");
                else
                    emit("execute store result " + at + " double " + decimal(1.0 / SCALE)
                         + " run scoreboard players get " + score(holders[i]));
            }
            run = "function " + commandFile(s.text) + " with storage mcl:args";
        }

        if (!s.dst) {
            emit(run);
            return;
        }
        const std::string holder = "$" + s.dst->toString();
        emit("execute store " + std::string(s.store == ImcCMD::Store::Success ? "success" : "result") + " score "
             + score(holder) + " run " + run);
        emit(opLine(holder, "*=", "#scale"));
    }

    // One file per distinct command, shared by every place that runs it.
    std::string McGen::commandFile(const std::string &text) {
        auto it = m_commands.find(text);
        if (it != m_commands.end())
            return it->second;

        std::string macro; // the text with $(a0), $(a1), ... in its holes
        std::size_t arg = 0;
        for (std::size_t i = 0; i < text.size(); ++i) {
            if (text[i] == '{' && i + 1 < text.size() && text[i + 1] == '}') {
                macro += "$(a" + std::to_string(arg++) + ")";
                ++i;
                continue;
            }
            macro += text[i];
        }

        const std::string path = "rt/cmd" + std::to_string(m_commands.size());
        // `return run` hands the command's success and result back to the caller.
        m_files[path] = {"# Macro: " + text, "$return run " + macro};
        const std::string name = "mcl:" + path;
        m_commands[text] = name;
        return name;
    }

    void McGen::visit(ImcJUMP &s) {
        emit(jumpTo(s.label.name));
        m_terminated = true;
    }

    void McGen::visit(ImcCJUMP &s) {
        // Optimized, a comparison jumps on the comparison itself instead of first
        // turning it into 0 or 1000 and testing that.
        auto *compare = dynamic_cast<ImcBINOP *>(s.cond.get());
        const auto *wide = compare ? dynamic_cast<ImcMEM *>(compare->fst.get()) : nullptr;
        if (m_optimize && compare && !(wide && wide->size > SLOT_SIZE)) {
            using Oper = ImcBINOP::Oper;
            static const std::unordered_map<Oper, const char *> ops = {
                {Oper::LTH, "<"}, {Oper::GTH, ">"}, {Oper::LEQ, "<="}, {Oper::GEQ, ">="},
                {Oper::EQU, "="}, {Oper::NEQ, "="}};
            if (auto op = ops.find(compare->oper); op != ops.end()) {
                const std::string a = gen(*compare->fst);
                const std::string b = gen(*compare->snd);
                emit(std::string("execute ") + (compare->oper == Oper::NEQ ? "unless" : "if") + " score "
                     + score(a) + " " + op->second + " " + score(b) + " run " + jumpTo(s.pos.name));
                emit(jumpTo(s.neg.name));
                m_terminated = true;
                return;
            }
        }

        const std::string cond = gen(*s.cond);
        emit("execute unless score " + score(cond) + " matches 0 run " + jumpTo(s.pos.name));
        emit(jumpTo(s.neg.name));
        m_terminated = true;
    }

    void McGen::visit(ImcLABEL &) {} // genChunk starts a new block at every label

    void McGen::visit(ImcSTMTS &) { error("STMTS left in linearized code"); }
